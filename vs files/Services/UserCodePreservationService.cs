using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading.Tasks;

namespace Snapcode.Services
{
    /// <summary>
    /// Prevents conflicts between visual designer/Blockly code generation and custom Dart code.
    /// Preserves user-written imports, class members, lifecycle logic, custom methods, and event bodies.
    /// </summary>
    public static class UserCodePreservationService
    {
        // Standard marker tags
        public const string TagImports = "IMPORTS";
        public const string TagClassMembers = "CLASS_MEMBERS";
        public const string TagInitState = "INIT_STATE";
        public const string TagDispose = "DISPOSE";
        public const string TagCustomMethods = "CUSTOM_METHODS";
        public const string TagOrphanedCode = "ORPHANED_CODE";

        // Regex matching: // <!-- USER_CODE_START: {tag} --> ... // <!-- USER_CODE_END: {tag} -->
        // Supports empty marker pairs (START\nEND) as well as non-empty blocks
        private static readonly Regex MarkerRegex = new Regex(
            @"//\s*<!--\s*USER_CODE_START:\s*(?<tag>[A-Za-z0-9_-]+)\s*-->[ \t]*\r?\n(?<code>.*?)//\s*<!--\s*USER_CODE_END:\s*\k<tag>\s*-->",
            RegexOptions.Singleline | RegexOptions.Compiled);

        /// <summary>
        /// Reads an existing Dart file and extracts all user-written code blocks indexed by their tag.
        /// Also detects un-tagged custom imports and methods to ensure zero code loss.
        /// </summary>
        public static Dictionary<string, string> ExtractUserCodeBlocks(string existingSource)
        {
            var blocks = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            if (string.IsNullOrWhiteSpace(existingSource)) return blocks;

            var matches = MarkerRegex.Matches(existingSource);
            foreach (Match match in matches)
            {
                string tag = match.Groups["tag"].Value.Trim();
                string code = match.Groups["code"].Value.Trim();
                if (!string.IsNullOrWhiteSpace(code))
                {
                    blocks[tag] = code;
                }
            }

            // Heuristic fallback: if user wrote custom imports outside markers
            var customImports = ExtractUntaggedImports(existingSource);
            if (!string.IsNullOrWhiteSpace(customImports))
            {
                if (blocks.TryGetValue(TagImports, out string? existingImports))
                {
                    if (!existingImports.Contains(customImports.Trim()))
                    {
                        blocks[TagImports] = (existingImports + "\n" + customImports).Trim();
                    }
                }
                else
                {
                    blocks[TagImports] = customImports.Trim();
                }
            }

            // Sanitize custom methods and orphaned code: strip any auto-generated event bindings
            // (e.g. // EVENT_BINDING:, showDialog, Navigator) so they are recognized as generated code,
            // never preserved or duplicated as custom methods or orphaned code.
            if (blocks.TryGetValue(TagCustomMethods, out string? customMethods))
            {
                string sanitized = RemoveAutoGeneratedEventBindings(customMethods);
                if (string.IsNullOrWhiteSpace(sanitized))
                {
                    blocks.Remove(TagCustomMethods);
                }
                else
                {
                    blocks[TagCustomMethods] = sanitized;
                }
            }

            if (blocks.TryGetValue(TagOrphanedCode, out string? orphanedCode))
            {
                string sanitized = RemoveAutoGeneratedEventBindings(orphanedCode);
                if (string.IsNullOrWhiteSpace(sanitized) || IsOnlyPreservedCodeHeaders(sanitized))
                {
                    blocks.Remove(TagOrphanedCode);
                }
                else
                {
                    blocks[TagOrphanedCode] = sanitized;
                }
            }

            return blocks;
        }

        private static string RemoveAutoGeneratedEventBindings(string code)
        {
            if (string.IsNullOrWhiteSpace(code)) return "";
            var lines = code.Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None);
            var sb = new StringBuilder();
            bool skippingBinding = false;

            foreach (var line in lines)
            {
                string trimmed = line.Trim();
                if (trimmed.StartsWith("// EVENT_BINDING:"))
                {
                    skippingBinding = true;
                    continue;
                }

                if (skippingBinding)
                {
                    if (trimmed.StartsWith("showDialog") || trimmed.StartsWith("Navigator.") || string.IsNullOrWhiteSpace(trimmed))
                    {
                        continue;
                    }
                    skippingBinding = false;
                }

                sb.AppendLine(line);
            }

            return sb.ToString().Trim();
        }

        private static bool IsOnlyPreservedCodeHeaders(string code)
        {
            var lines = code.Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None);
            foreach (var line in lines)
            {
                string trimmed = line.Trim();
                if (!string.IsNullOrWhiteSpace(trimmed) && !trimmed.StartsWith("//"))
                {
                    return false;
                }
            }
            return true;
        }

        private static string ExtractUntaggedImports(string source)
        {
            var sb = new StringBuilder();
            var lines = source.Split('\n');
            bool insideMarker = false;

            foreach (var rawLine in lines)
            {
                string line = rawLine.Trim();
                if (line.Contains("<!-- USER_CODE_START:")) insideMarker = true;
                if (line.Contains("<!-- USER_CODE_END:")) insideMarker = false;

                // Only extract non-framework custom user imports. Never extract standard Flutter SDK packages.
                if (!insideMarker && line.StartsWith("import ") && 
                    !line.Contains("'package:flutter/") && !line.Contains("\"package:flutter/"))
                {
                    sb.AppendLine(line);
                }
            }
            return sb.ToString().Trim();
        }

        /// <summary>
        /// Creates a marker block with optional default content.
        /// </summary>
        public static string FormatMarkerBlock(string tag, string defaultContent = "")
        {
            var sb = new StringBuilder();
            sb.AppendLine($"// <!-- USER_CODE_START: {tag} -->");
            if (!string.IsNullOrEmpty(defaultContent))
            {
                sb.AppendLine(defaultContent);
            }
            sb.Append($"// <!-- USER_CODE_END: {tag} -->");
            return sb.ToString();
        }

        public static string MergeUserCodeIntoGenerated(string generatedTemplate, Dictionary<string, string> preservedBlocks)
        {
            return MergePreservedCode(generatedTemplate, preservedBlocks);
        }

        /// <summary>
        /// Merges preserved user code blocks into freshly generated code templates.
        /// Never overwrites user code and safely stores orphaned blocks.
        /// </summary>
        public static string MergePreservedCode(string generatedTemplate, Dictionary<string, string> preservedBlocks)
        {
            if (preservedBlocks == null || preservedBlocks.Count == 0)
                return generatedTemplate;

            string templateWithMarkers = EnsurePreservationMarkers(generatedTemplate);
            var usedTags = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            string mergedCode = MarkerRegex.Replace(templateWithMarkers, match =>
            {
                string tag = match.Groups["tag"].Value.Trim();
                usedTags.Add(tag);

                if (preservedBlocks.TryGetValue(tag, out string? userCode) && !string.IsNullOrWhiteSpace(userCode))
                {
                    return $"// <!-- USER_CODE_START: {tag} -->\n{userCode.TrimEnd()}\n// <!-- USER_CODE_END: {tag} -->";
                }

                return match.Value;
            });

            // If TagImports was preserved but not matched in template (defensive fallback), insert at top after imports
            if (!usedTags.Contains(TagImports) && preservedBlocks.TryGetValue(TagImports, out string? extraImports) && !string.IsNullOrWhiteSpace(extraImports))
            {
                usedTags.Add(TagImports);
                mergedCode = $"// <!-- USER_CODE_START: {TagImports} -->\n{extraImports.Trim()}\n// <!-- USER_CODE_END: {TagImports} -->\n\n" + mergedCode;
            }

            // Safeguard against deleted or renamed widget event markers: preserve as ORPHANED_CODE
            // NEVER orphan TagImports - imports must never be placed at the bottom of a Dart file!
            var orphanedBlocks = new List<string>();
            foreach (var kvp in preservedBlocks)
            {
                if (!usedTags.Contains(kvp.Key) && 
                    !string.IsNullOrWhiteSpace(kvp.Value) && 
                    !kvp.Key.Equals(TagOrphanedCode, StringComparison.OrdinalIgnoreCase) &&
                    !kvp.Key.Equals(TagImports, StringComparison.OrdinalIgnoreCase))
                {
                    // Clean out any lines that are import statements to prevent fatal Dart directive errors
                    var nonImportLines = kvp.Value.Split(new[] { "\r\n", "\r", "\n" }, StringSplitOptions.None)
                        .Where(l => !l.Trim().StartsWith("import "));
                    string cleanedVal = string.Join("\n", nonImportLines).Trim();
                    if (!string.IsNullOrWhiteSpace(cleanedVal) && !IsOnlyPreservedCodeHeaders(cleanedVal))
                    {
                        orphanedBlocks.Add($"// [PRESERVED CUSTOM CODE FOR: {kvp.Key}]\n{cleanedVal}");
                    }
                }
            }

            if (orphanedBlocks.Count > 0)
            {
                mergedCode += "\n\n// ==========================================\n" +
                              $"// <!-- USER_CODE_START: {TagOrphanedCode} -->\n" +
                              string.Join("\n\n", orphanedBlocks) +
                              $"\n// <!-- USER_CODE_END: {TagOrphanedCode} -->\n" +
                              "// ==========================================\n";
            }

            return mergedCode;
        }

        /// <summary>
        /// Reads existing file, merges preserved user code with new generated code, and writes safely (synchronous).
        /// </summary>
        public static void SaveDartFileWithPreservation(string filePath, string newGeneratedCode)
        {
            Dictionary<string, string> existingBlocks = new();

            if (File.Exists(filePath))
            {
                try
                {
                    string existingSource = File.ReadAllText(filePath);
                    existingBlocks = ExtractUserCodeBlocks(existingSource);
                }
                catch (Exception ex)
                {
                    System.Diagnostics.Debug.WriteLine($"[UserCodePreservation] Failed reading {filePath}: {ex.Message}");
                }
            }

            string finalCode = MergePreservedCode(newGeneratedCode, existingBlocks);

            string? dir = Path.GetDirectoryName(filePath);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
            {
                Directory.CreateDirectory(dir);
            }

            File.WriteAllText(filePath, finalCode);
        }

        /// <summary>
        /// Reads existing file, merges preserved user code with new generated code, and writes safely (async).
        /// </summary>
        public static async Task SaveDartFileWithPreservationAsync(string filePath, string newGeneratedCode)
        {
            Dictionary<string, string> existingBlocks = new();

            if (File.Exists(filePath))
            {
                try
                {
                    string existingSource = await File.ReadAllTextAsync(filePath).ConfigureAwait(false);
                    existingBlocks = ExtractUserCodeBlocks(existingSource);
                }
                catch (Exception ex)
                {
                    System.Diagnostics.Debug.WriteLine($"[UserCodePreservation] Failed reading {filePath}: {ex.Message}");
                }
            }

            string finalCode = MergePreservedCode(newGeneratedCode, existingBlocks);

            string? dir = Path.GetDirectoryName(filePath);
            if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
            {
                Directory.CreateDirectory(dir);
            }

            await File.WriteAllTextAsync(filePath, finalCode).ConfigureAwait(false);
        }

        /// <summary>
        /// Wraps generated Dart page code in standard preservation markers if they are not already present.
        /// </summary>
        public static string EnsurePreservationMarkers(string dartCode)
        {
            if (string.IsNullOrWhiteSpace(dartCode)) return dartCode;

            if (dartCode.Contains("<!-- USER_CODE_START:"))
            {
                return dartCode; // Markers already present
            }

            var sb = new StringBuilder();

            // 1. Imports region
            sb.AppendLine("// ==========================================");
            sb.AppendLine(FormatMarkerBlock(TagImports, "// Add custom imports here (e.g. package:http/http.dart)"));
            sb.AppendLine("// ==========================================");
            sb.AppendLine();

            // Insert body
            sb.AppendLine(dartCode);

            // 2. Custom Methods region
            sb.AppendLine();
            sb.AppendLine("// ==========================================");
            sb.AppendLine(FormatMarkerBlock(TagCustomMethods, "// Add custom functions, API calls, and business logic here"));
            sb.AppendLine("// ==========================================");

            return sb.ToString();
        }
    }
}
