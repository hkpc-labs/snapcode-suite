import { generateDartFromAST } from './dartEmitter.js';

/**
 * Build a complete Flutter project from workspace AST.
 *
 * @param {object} workspaceJson - The Blockly AST JSON
 * @param {object} config - Project configuration
 * @returns {object} Map of file paths to file contents
 */
export function buildFlutterProject(workspaceJson, config = {}) {
  const appName = config.app_package_name || 'com.snapcode.app';
  const projectName = config.project_name || 'snapcode_app';
  const flutterSdk = config.flutter_sdk_version || '3.24.0';
  const dartSdk = config.dart_sdk_version || '3.5.0';

  // Generate Dart code from AST
  const mainDartCode = generateDartFromAST(workspaceJson);

  // Build file map
  const files = {};

  // ── lib/main.dart ───────────────────────────────────────
  files['lib/main.dart'] = mainDartCode;

  // ── pubspec.yaml ────────────────────────────────────────
  files['pubspec.yaml'] = `name: ${projectName}
description: A Flutter app generated by SnapCode
publish_to: 'none'
version: 1.0.0+1

environment:
  sdk: '>=${dartSdk} <4.0.0'

dependencies:
  flutter:
    sdk: flutter
  cupertino_icons: ^1.0.8

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^4.0.0

flutter:
  uses-material-design: true
`;

  // ── analysis_options.yaml ───────────────────────────────
  files['analysis_options.yaml'] = `include: package:flutter_lints/flutter.yaml

linter:
  rules:
    prefer_const_constructors: false
    prefer_const_literals_to_create_immutables: false
`;

  // ── README.md ───────────────────────────────────────────
  files['README.md'] = `# ${projectName}

Generated by **SnapCode** — Visual Block Coding → Flutter Apps

## Getting Started

1. Install Flutter: https://flutter.dev/docs/get-started/install
2. Run the app:

\`\`\`bash
flutter pub get
flutter run
\`\`\`

## Project Structure

\`\`\`
lib/
  main.dart     # Generated Flutter application
pubspec.yaml    # Dependencies and metadata
\`\`\`

---

*Built with SnapCode — https://snapcode.dev*
`;

  // ── .gitignore ──────────────────────────────────────────
  files['.gitignore'] = `# Flutter
.dart_tool/
.packages
build/
*.iml
.idea/
.vscode/
*.lock
`;

  return files;
}

/**
 * Create a ZIP file from a map of file paths to contents.
 * Uses a minimal ZIP implementation that works in Workers runtime.
 *
 * @param {object} files - Map of { 'path/file.ext': 'contents' }
 * @returns {Uint8Array} ZIP file as bytes
 */
export function createZip(files) {
  const entries = [];
  let offset = 0;

  // Build local file entries
  for (const [path, content] of Object.entries(files)) {
    const nameBytes = new TextEncoder().encode(path);
    const dataBytes = new TextEncoder().encode(content);

    // Local file header (30 bytes + name + data)
    const header = new Uint8Array(30 + nameBytes.length);
    const view = new DataView(header.buffer);

    view.setUint32(0, 0x04034b50, true); // Local file header signature
    view.setUint16(4, 20, true);          // Version needed
    view.setUint16(6, 0, true);           // Flags
    view.setUint16(8, 0, true);           // Compression (0 = stored)
    view.setUint16(10, 0, true);          // Mod time
    view.setUint16(12, 0, true);          // Mod date
    view.setUint32(14, crc32(dataBytes), true); // CRC-32
    view.setUint32(18, dataBytes.length, true);  // Compressed size
    view.setUint32(22, dataBytes.length, true);  // Uncompressed size
    view.setUint16(26, nameBytes.length, true);  // Filename length
    view.setUint16(28, 0, true);          // Extra field length

    header.set(nameBytes, 30);

    entries.push({
      header,
      data: dataBytes,
      name: nameBytes,
      offset,
      crc: crc32(dataBytes),
      size: dataBytes.length,
    });

    offset += header.length + dataBytes.length;
  }

  // Build central directory
  const centralDir = [];
  for (const entry of entries) {
    const cd = new Uint8Array(46 + entry.name.length);
    const cdView = new DataView(cd.buffer);

    cdView.setUint32(0, 0x02014b50, true);  // Central dir signature
    cdView.setUint16(4, 20, true);            // Version made by
    cdView.setUint16(6, 20, true);            // Version needed
    cdView.setUint16(8, 0, true);             // Flags
    cdView.setUint16(10, 0, true);            // Compression
    cdView.setUint16(12, 0, true);            // Mod time
    cdView.setUint16(14, 0, true);            // Mod date
    cdView.setUint32(16, entry.crc, true);    // CRC-32
    cdView.setUint32(20, entry.size, true);   // Compressed size
    cdView.setUint32(24, entry.size, true);   // Uncompressed size
    cdView.setUint16(28, entry.name.length, true); // Filename length
    cdView.setUint16(30, 0, true);            // Extra field length
    cdView.setUint16(32, 0, true);            // Comment length
    cdView.setUint16(34, 0, true);            // Disk number
    cdView.setUint16(36, 0, true);            // Internal attrs
    cdView.setUint32(38, 0, true);            // External attrs
    cdView.setUint32(42, entry.offset, true); // Offset of local header
    cd.set(entry.name, 46);

    centralDir.push(cd);
  }

  // Calculate sizes
  const cdSize = centralDir.reduce((sum, cd) => sum + cd.length, 0);

  // End of central directory
  const eocd = new Uint8Array(22);
  const eocdView = new DataView(eocd.buffer);
  eocdView.setUint32(0, 0x06054b50, true);  // EOCD signature
  eocdView.setUint16(4, 0, true);            // Disk number
  eocdView.setUint16(6, 0, true);            // CD disk number
  eocdView.setUint16(8, entries.length, true); // Entries on disk
  eocdView.setUint16(10, entries.length, true); // Total entries
  eocdView.setUint32(12, cdSize, true);        // CD size
  eocdView.setUint32(16, offset, true);        // CD offset
  eocdView.setUint16(20, 0, true);             // Comment length

  // Concatenate everything
  const totalSize = offset + cdSize + 22;
  const zipData = new Uint8Array(totalSize);
  let pos = 0;

  for (const entry of entries) {
    zipData.set(entry.header, pos);
    pos += entry.header.length;
    zipData.set(entry.data, pos);
    pos += entry.data.length;
  }
  for (const cd of centralDir) {
    zipData.set(cd, pos);
    pos += cd.length;
  }
  zipData.set(eocd, pos);

  return zipData;
}

// ── CRC-32 Implementation ─────────────────────────────────
const crc32Table = (() => {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let j = 0; j < 8; j++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[i] = c;
  }
  return table;
})();

function crc32(data) {
  let crc = 0xffffffff;
  for (let i = 0; i < data.length; i++) {
    crc = crc32Table[(crc ^ data[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
